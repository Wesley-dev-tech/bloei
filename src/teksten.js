// Zoekt een tekst met punt-notatie en vervangt {plaatshouders}.
// Een ontbrekende sleutel geeft de sleutel zelf terug, met een waarschuwing in de console.
// Een warme zin uit de motivatie, met de voornaam erin. De naam staat in de zinnen altijd als ", {naam}"; is er geen naam, dan
// vervalt dat stuk en blijft de zin heel. Alleen de voornaam telt (zoals bij de begroeting).
export function warmeZin(sleutel, naam = '', waarden = {}) {
  const voornaam = voornaamVan(naam);
  const tekst = t(sleutel, waarden);
  // De vervanging is een functie: een naam met $&, $', $` of $$ komt zo letterlijk in de zin (een tekst als vervanging leest replaceAll als patroon).
  return voornaam ? tekst.replaceAll('{naam}', () => voornaam) : tekst.replaceAll(', {naam}', '');
}

// De zin van de motivator (logica/motivatie.js, kiesMotivatie): de sleutel plus wat erin komt. Een medaille komt binnen als id en wordt
// haar naam; de duur van "zo lang gebruik je Bloei" komt binnen als woord (motivatieWoord.periode).
export function motivatieZin(keuze, naam = '') {
  const waarden = { ...(keuze?.waarden ?? {}) };
  if (waarden.badge) waarden.badge = t('badge.namen.' + waarden.badge);
  if (waarden.periode) waarden.periode = t('motivatieWoord.periode.' + waarden.periode);
  return warmeZin(keuze.sleutel, naam, waarden);
}

export function t(sleutel, waarden = {}) {
  let tekst = sleutel.split('.').reduce((o, deel) => (o == null ? o : o[deel]), TEKSTEN);
  if (typeof tekst !== 'string') {
    console.warn('Tekst ontbreekt:', sleutel);
    return sleutel;
  }
  // Als functie: een waarde met $&, $', $`, $1 of $$ (een profielnaam, een supplementnaam) komt letterlijk in de zin.
  for (const [naam, waarde] of Object.entries(waarden)) tekst = tekst.replaceAll('{' + naam + '}', () => String(waarde));
  return tekst;
}
